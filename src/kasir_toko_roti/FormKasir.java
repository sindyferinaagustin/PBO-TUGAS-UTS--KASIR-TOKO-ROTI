    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int baris = tblKeranjang.getSelectedRow();
        if (baris < 0) {
            JOptionPane.showMessageDialog(this, "Pilih baris yang akan dihapus");
            return;
        }
        keranjang.remove(baris);
        tampilkanKeranjang();
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
        if (keranjang.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Keranjang masih kosong");
        return;
        }
        try {
            double bayar = Double.parseDouble(txtBayar.getText().trim());
            if (bayar < total) {
                JOptionPane.showMessageDialog(this, "Uang pembayaran kurang");
                return;
            }
            double kembali = bayar - total;
            lblKembali.setText(String.format("Kembalian: Rp %,.0f", kembali));
            cetakStruk(bayar, kembali);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Uang bayar harus berupa angka");
        }

    }//GEN-LAST:event_btnBayarActionPerformed

    private void btnBaruActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBaruActionPerformed
        keranjang.clear();
        tampilkanKeranjang();
        txtBayar.setText("");
        lblKembali.setText("Kembalian: Rp 0");
        txtStruk.setText("");
    }//GEN-LAST:event_btnBaruActionPerformed

