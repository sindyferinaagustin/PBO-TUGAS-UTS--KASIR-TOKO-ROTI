    private void tampilHarga() {
    int pilih = cmbProduk.getSelectedIndex();
    if (pilih < 0) {
        return;   
    }
    Produk p = daftarProduk.get(pilih);
    lblHarga.setText(String.format("Harga: Rp %,.0f", p.getHarga()));
}
    
    private void tampilkanKeranjang() {
    model.setRowCount(0);
    total = 0;
    for (ItemTransaksi item : keranjang) {
        Produk p = item.getProduk();
      
        model.addRow(new Object[]{
            p.getNama(), p.getJenis(), item.getJumlah(),
            String.format("Rp %,.0f", item.getSubtotal())
        });
        total += item.getSubtotal();
    }
    lblTotal.setText(String.format("Total: Rp %,.0f", total));
    }

    private void cetakStruk(double bayar, double kembali) {
        StringBuilder sb = new StringBuilder();

        sb.append("====================================\n");
        sb.append("              S I F E A\n");
        sb.append("              B A K E R Y\n");
        sb.append("        Fresh Bread, Happy Heart!\n");
        sb.append("====================================\n");
        sb.append("           STRUK PEMBELIAN\n");
        sb.append("------------------------------------\n");
        sb.append(String.format("%-16s %4s %10s\n",
                "Produk", "Qty", "Subtotal"));
        sb.append("------------------------------------\n");

        for (ItemTransaksi item : keranjang) {
            sb.append(String.format("%-16s %4d %10s\n",
                    item.getProduk().getNama(),
                    item.getJumlah(),
                    String.format("%,.0f", item.getSubtotal())));
        }

        sb.append("------------------------------------\n");
        sb.append(String.format("%-20s Rp %10s\n",
                "TOTAL",
                String.format("%,.0f", total)));
        sb.append(String.format("%-20s Rp %10s\n",
                "BAYAR",
                String.format("%,.0f", bayar)));
        sb.append(String.format("%-20s Rp %10s\n",
                "KEMBALI",
                String.format("%,.0f", kembali)));
        sb.append("====================================\n");
        sb.append("      Terima kasih telah membeli\n");
        sb.append("         di Sifea Bakery!\n");
        sb.append("      Semoga harimu semanis roti.\n");
        sb.append("====================================\n");

        txtStruk.setText(sb.toString());
    }

